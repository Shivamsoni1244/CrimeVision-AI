import React from 'react';
import { Cites, Spinner, ErrorBox } from './common.jsx';

const List = ({ title, items }) => (items?.length ? <div className="sub"><h4>{title}</h4><ul>{items.map((x, i) => <li key={i}>{x}</li>)}</ul></div> : null);

// `a` is exactly what Flask returned (image `assessment` or /api/classify result). Nothing here is generated client-side.
export default function Assessment({ a, busy, error, onClassify, canClassify = true }) {
  return (
    <div className="assessment">
      <div className="banner">AI-generated preliminary analysis. Requires human review; not a finding of fact or guilt.</div>
      {onClassify && (
        <div className="row">
          <button className="btn primary" onClick={onClassify} disabled={busy || !canClassify}>{busy ? <Spinner label="Classifying…" /> : 'Classify case'}</button>
          {!canClassify && <span className="muted">Analyse evidence first.</span>}
        </div>
      )}
      <ErrorBox error={error} />
      {!a ? <p className="empty">No assessment yet.</p> : a.status === 'unavailable' ? (
        <div className="alert warn">Assessment unavailable: {a.error}</div>
      ) : (
        <>
          <div className="verdict">
            <span className={`badge cat ${a.category === 'Insufficient evidence' ? 'muted' : ''}`}>{a.category}</span>
            <span className="muted">model confidence {Math.round((a.confidence ?? 0) * 100)}% (an LLM estimate, not a measured probability)</span>
          </div>
          {a.reasoning && <p>{a.reasoning}</p>}
          {a.scenario && <div className="sub"><h4>Possible scenario (interpretation)</h4><p>{a.scenario}</p></div>}
          {a.supporting_observations?.length > 0 && (
            <div className="sub"><h4>Supporting observations (each cites a real record)</h4>
              <ul>{a.supporting_observations.map((s, i) => <li key={i}>{s.text} <Cites ids={s.citations} /></li>)}</ul></div>
          )}
          <List title="Uncertainties" items={a.uncertainties} />
          <List title="Alternative explanations" items={a.alternative_explanations} />
          <List title="Missing information" items={a.missing_information} />
          <List title="Recommended follow-up" items={a.recommended_follow_up} />
          {a.validation_notes?.length > 0 && <div className="alert warn"><strong>Validation notes:</strong> {a.validation_notes.join(' ')}</div>}
          {a.limitations?.length > 0 && <details><summary>Model limitations</summary><p>{a.limitations.join(' ')}</p></details>}
          {a.generated_by && <p className="muted small">Generated by {a.generated_by.model} at {a.generated_by.generated_at}</p>}
        </>
      )}
    </div>
  );
}
